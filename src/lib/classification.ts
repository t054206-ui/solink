/** A value with provenance. Use for anything displayed as a metric. */
export interface Classified<T = number> {
  value: T | null;
  cls: DataClass;
  /** Short source description, e.g. "Manufacturer datasheet", "WeatherAPI.com", "Solink calculator" */
  source?: string;
  /** Assumptions or notes that materially affect interpretation */
  notes?: string[];
  /** If unavailable, why (often a placeholder string) */
  reason?: string;
}

export function unavailable<T = number>(reason: string): Classified<T> {
  return { value: null, cls: "unavailable", reason };
}

export function classified<T>(value: T, cls: DataClass, source?: string, notes?: string[]): Classified<T> {
  return { value, cls, source, notes };
}
