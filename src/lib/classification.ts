/**
 * Data classification used everywhere in Solink.
 * Every number shown to a user should carry one of these labels.
 */
export type DataClass =
  | "source"       // REAL / SOURCE DATA: directly from a trusted source (manufacturer, weather API, hardware)
  | "calculated"   // CALCULATED: deterministic math on real inputs
  | "estimated"    // ESTIMATED: based on assumptions or estimation models
  | "ai"           // AI INTERPRETATION: generated by Claude from available data
  | "demo"         // DEMO DATA — NOT REAL
  | "user"         // USER-PROVIDED: entered by the user (an input, not a verified fact)
  | "unavailable"; // Not enough data / integration not connected

